const scales: ScaleDef[] = DOMAINS.flatMap((d) => [
  { id: d.id, label: d.label, description: d.description, lowLabel: d.low, highLabel: d.high },
  ...d.facets.map(([id, label, description, lowLabel, highLabel]) => ({
    id,
    label,
    description,
    lowLabel,
    highLabel,
    parent: d.id,
  })),
]);

const allItems: (ItemDef & { quick: boolean })[] = DOMAINS.flatMap((d) =>
  d.facets.flatMap(([facetId, , , , , items]) =>
    items.map(([text, keyed], i) => ({
      id: `${facetId.toLowerCase()}-${i + 1}`,
      text,
      scale: facetId,
      keyed,
      quick: i < 2,
    })),
  ),
);

