/** 上位 3 つの頭文字（同点は RIASEC の順） */
export function riasecCode(pomp: Record<string, number>): string {
  return RIASEC_TYPES.map((t) => t.id)
    .sort((a, b) => (pomp[b] ?? 0) - (pomp[a] ?? 0))
    .slice(0, 3)
    .join('');
}
