const AXES = ['E', 'O', 'A', 'C'] as const;

/** 得点からタイプを決める（50 以上を高いとする） */
export function growTypeOf(scores: ScaleScore[]): GrowType & { stable: boolean } {
  const map = scoreMap(scores);
  const bits = AXES.map((a) => ((map[a]?.pomp ?? 50) >= 50 ? '+' : '-')).join('') as Bits;
  const code = AXES.map((a, i) => `${a}${bits[i]}`).join('');
  return { code, ...TYPES[bits], stable: (map.N?.pomp ?? 50) < 50 };
}

